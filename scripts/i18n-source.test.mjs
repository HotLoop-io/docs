import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parse, segs, hashes, diff, headingSlugs } from './i18n-source.mjs';

const page = (body) => `---\ntitle: "T"\ndescription: "D"\n---\n\n${body}\n`;

test('front matter and prose are segments, code and blank lines are not', () => {
  const s = segs(parse(page('One.\n\n```bash\necho hi\n```\n\n## Two\n\n| a | b |\n|---|---|\n| 1 | 2 |')));
  assert.deepEqual(s, ['title: "T"', 'description: "D"', 'One.', '## Two', '| a | b |', '| 1 | 2 |']);
});

test('a soft wrapped paragraph is one segment, a list item and a heading are not joined', () => {
  const s = segs(parse(page('first line\nsecond line\n\n- item one\n  continues\n- item two\n\n## H\nafter heading')));
  assert.deepEqual(s.slice(2), ['first line\nsecond line', '- item one\n  continues', '- item two', '## H', 'after heading']);
});

test('the sync header lines and the reviewed line are not segments', () => {
  const t = '---\n# generated by scripts/sync-docs.mjs\nreviewed: hotloop=4.23.2\ntitle: "T"\ndescription: "D"\neditUrl: false\n---\n\nBody.\n';
  assert.deepEqual(segs(parse(t)), ['title: "T"', 'description: "D"', 'Body.']);
});

test('diff names the changed and the removed segment and keeps the rest in place', () => {
  const a = ['a', 'b', 'c', 'd'], b = ['a', 'x', 'c', 'd', 'e'];
  const d = diff(a, b);
  assert.deepEqual(d.changed, [1, 4]);
  assert.deepEqual(d.removed, [1]);
  assert.deepEqual(d.carry, [0, -1, 2, 3, -1]);
});

test('a segment that moved keeps its translation', () => {
  const d = diff(['a', 'b', 'c'], ['b', 'c', 'a']);
  assert.equal(d.changed.length + d.removed.length, 2);
});

test('hashes change with the text and not with the line ending', () => {
  assert.deepEqual(hashes(page('A')), hashes(page('A').replace(/\n/g, '\r\n')));
  assert.notDeepEqual(hashes(page('A')), hashes(page('B')));
});

test('heading slugs follow the page, with duplicates numbered', () => {
  assert.deepEqual(headingSlugs('# A\n\n## Same\n\n## Same\n\n```\n## no\n```'), ['a', 'same', 'same-1']);
});
