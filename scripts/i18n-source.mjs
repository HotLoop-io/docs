// Keeps every translated page tied to the English it was made from.
//
//   node scripts/i18n-source.mjs                      check (what `npm run build` and the sync run)
//   node scripts/i18n-source.mjs record <id> [lang..] record: these translations were made from the English as it is now
//   node scripts/i18n-source.mjs links [--fix]        check, or repair, the #anchor on every link between translated pages
//   node scripts/i18n-source.mjs stale --json         the stale segments as data, for the retranslation tools
//   node scripts/i18n-source.mjs releases [--write]   the release notes pages still without their 13 translations; --write drops the translated ones from the pending list
//
// How it works. A page is cut into segments: its front matter title, description and sidebar label, then every
// line of the body that is not code, a table rule, a blank line or a bare HTML or import line. A translation holds
// one translated line per English segment, in the same order. When a translation is made, the sha256 (first 12
// hex digits) of each English segment is written to src/i18n-source/<page with / as __>.json, per language. The
// check cuts the English page again and lines the two lists up (longest common subsequence), so a segment that
// moved keeps its translation and a segment that changed or is new is named: page, language, segment number, line
// in the English file, and the new English text. A page that has a translation and no record fails too, and so
// does a record with no translation, a translation that no longer has the record's number of segments, and a link
// between translated pages whose #anchor is not a heading of the page it lands on.
//
// English comes from src/pinned/<page>.md when the page is pinned (hand-written, {{hotloop}} style tokens kept, so a
// version bump is not a change), and from src/content/docs/<page>.md or .mdx otherwise (generated by the sync, or
// hand-written). The sync calls report() with the pages it just wrote, so a stale translation is named in the same
// run that made it stale.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import GithubSlugger from 'github-slugger';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const FOLDERS = ['es', 'fr', 'it', 'de', 'nb', 'bg', 'el', 'ko', 'ja', 'vi', 'hi', 'zh-hans', 'ar'];
export const RECORDS = 'src/i18n-source';
const CONTENT = 'src/content/docs';
const PINNED = 'src/pinned';

// ---- segments ------------------------------------------------------------------------
// items: { raw } (kept as is) | { seg } (translated) | { drop } (written by the sync, never translated)
export function parse(text) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const items = [];
  let i = 0, fm = false, inFence = null;
  if (lines[0] === '---') { fm = true; items.push({ raw: '---' }); i = 1; }
  for (; i < lines.length; i++) {
    const l = lines[i];
    if (fm) {
      if (l === '---') { fm = false; items.push({ raw: l }); continue; }
      if (/^(reviewed:|# generated|editUrl:)/.test(l)) { items.push({ drop: true }); continue; }
      if (/^(title|description): /.test(l) || /^  label: /.test(l)) items.push({ seg: l, fm: true }); else items.push({ raw: l });
      continue;
    }
    if (inFence) { items.push({ raw: l }); if (l.trim().startsWith(inFence)) inFence = null; continue; }
    const f = /^\s*(```+|~~~+)/.exec(l);
    if (f) { inFence = f[1]; items.push({ raw: l }); continue; }
    if (l.trim() === '' || /^\s*\|[\s:|-]+\|\s*$/.test(l) || /^:::\w*\s*$/.test(l) || /^\s*<|^import /.test(l) || /^---+$/.test(l.trim())) { items.push({ raw: l }); continue; }
    // A soft-wrapped paragraph or list item is one segment, so a translation that unwraps it still lines up. A line
    // joins the one above only when both are plain prose: not a heading, list marker, table row, quote, aside, image
    // or HTML line, and the line above is not front matter.
    let prev = items[items.length - 1];
    if (prev && prev.joined) prev = items[prev.of];
    if (prev && prev.seg !== undefined && !prev.fm && wrapsInto(prev.text, l)) { prev.seg += '\n' + l; items.push({ drop: true, joined: true, of: items.indexOf(prev) }); continue; }
    items.push({ seg: l, text: l });
  }
  return items;
}
const BLOCK = /^\s*(#{1,6}\s|[-*+]\s|\d+[.)]\s|\||>|:::|!\[|<)/;
function wrapsInto(prevLine, line) {
  if (BLOCK.test(line) || /^\s*---+\s*$/.test(line)) return false;
  if (/^\s*(#{1,6}\s|\||>|:::|!\[|<)/.test(prevLine)) return false;
  return true;
}
export const segs = (items) => items.filter((x) => x.seg !== undefined).map((x) => x.seg);
export const hashSeg = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
export const hashes = (text, versions = null) => segs(parse(text)).map((s) => hashSeg(normalizeVersions(s, versions)));

// Release versions are not wording. A page that says 4.23.2 where the product's latest release is 4.23.2 says
// {{hotloop}} as far as the translation is concerned, so a release that moves the number does not mark every
// translation stale. `versions` is the sync's map ({ hotloop: '4.23.2', flow: '2.16.6', cascade: '1.4.1' }).
// Three shapes are recognised, each only for the product's LATEST release: the full version, its x line (4.23.x),
// and its major.minor (4.23, never inside a longer number). Older versions in a release list stay as written,
// because they are history and do not move.
const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
export function normalizeVersions(s, versions) {
  if (!versions) return s;
  let out = s;
  for (const [name, ver] of Object.entries(versions)) {
    const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(ver ?? '');
    if (!m) continue;
    const full = esc(ver), line = esc(`${m[1]}.${m[2]}`);
    out = out.replace(new RegExp(`(?<![\\w.-])${full}(?![\\w]|\\.\\d|-\\d)`, 'g'), `{{${name}}}`)
      .replace(new RegExp(`(?<![\\w.-])${line}\\.x\\b`, 'g'), `{{${name}.x}}`)
      .replace(new RegExp(`(?<![\\w.-])${line}(?![\\w]|\\.\\d|-\\d)`, 'g'), `{{${name}.minor}}`);
  }
  return out;
}
// The line number (1-based) in the file of each segment.
const segLines = (text) => parse(text).flatMap((x, i) => (x.seg !== undefined ? [i + 1] : []));

// ---- headings and anchors -------------------------------------------------------------
const stripMd = (s) => s.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*`]/g, '').replace(/<[^>]+>/g, '').trim();
// A code fence opens with 3 or more backticks or tildes and closes only with the same character, at least as many.
// So a ```` block that shows a ``` fence inside it, or a ~~~ block that holds backticks, stays one block. Call it
// line by line with the open fence (or null); it returns the fence still open after the line and whether the line
// belongs to the code (the opening and closing lines included).
export function fenceStep(open, line) {
  if (open) {
    const c = /^\s*(`{3,}|~{3,})\s*$/.exec(line);
    return c && c[1][0] === open[0] && c[1].length >= open.length ? { open: null, code: true } : { open, code: true };
  }
  const f = /^\s*(`{3,}|~{3,})/.exec(line);
  return f ? { open: f[1], code: true } : { open: null, code: false };
}
export function headingSlugs(text) {
  const s = new GithubSlugger();
  const out = [];
  let fence = null;
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  let i = 0;
  if (lines[0] === '---') { i = 1; while (i < lines.length && lines[i] !== '---') i++; i++; } // a front matter comment line is not a heading
  for (; i < lines.length; i++) {
    const l = lines[i];
    const st = fenceStep(fence, l);
    fence = st.open;
    if (st.code) continue;
    const m = /^(#{1,6}) +(.*?)\s*#*$/.exec(l);
    if (m) out.push(s.slug(stripMd(m[2])));
  }
  return out;
}

// ---- files -----------------------------------------------------------------------------
// A view of the tree: the files on disk, with `overlay` (path under ROOT -> text) on top, so the sync can ask
// about the pages it is about to write.
function view(overlay = new Map()) {
  const exists = (p) => overlay.has(p) || existsSync(join(ROOT, p));
  const read = (p) => (overlay.has(p) ? overlay.get(p) : readFileSync(join(ROOT, p), 'utf8')).replace(/\r\n/g, '\n');
  const walk = (dir) => {
    const found = new Set();
    const d = join(ROOT, dir);
    const rec = (abs, rel) => {
      if (!existsSync(abs)) return;
      for (const n of readdirSync(abs)) {
        const a = join(abs, n), r = rel + '/' + n;
        if (statSync(a).isDirectory()) rec(a, r); else found.add(r);
      }
    };
    rec(d, dir);
    for (const k of overlay.keys()) if (k.startsWith(dir + '/')) found.add(k);
    return [...found].sort();
  };
  return { exists, read, walk };
}
// The latest release of each product, from the sync's own data, as the sync sees it (the overlay carries the file it is
// about to write). Empty when there is no sync data, and then nothing is normalized.
export function versionMap(v) {
  try {
    const repos = JSON.parse(v.read('src/data/sync.json')).repos ?? {};
    return Object.fromEntries(Object.entries(repos).flatMap(([k, r]) => (r?.release?.version ? [[k, r.release.version]] : [])));
  } catch { return {}; }
}
const idOf = (rel, base) => rel.slice(base.length + 1).replace(/\.mdx?$/, '');
const recordPath = (id) => `${RECORDS}/${id.replace(/\//g, '__')}.json`;

// Where the English of a page lives, or null.
function englishPath(v, id) {
  for (const p of [`${PINNED}/${id}.md`, `${CONTENT}/${id}.md`, `${CONTENT}/${id}.mdx`]) if (v.exists(p)) return p;
  return null;
}
// Where a language's translation of a page lives, or null. A pinned page's source is the pinned file; the
// content copy of it is what the sync writes from that.
function translationPath(v, lang, id) {
  for (const p of [`${PINNED}/${lang}/${id}.md`, `${CONTENT}/${lang}/${id}.md`, `${CONTENT}/${lang}/${id}.mdx`]) if (v.exists(p)) return p;
  return null;
}
// Every page that has a translation in some language, as { id, langs: Set }.
function translatedPages(v) {
  const pages = new Map();
  for (const lang of FOLDERS) {
    for (const base of [`${CONTENT}/${lang}`, `${PINNED}/${lang}`]) {
      for (const rel of v.walk(base)) {
        if (!/\.mdx?$/.test(rel)) continue;
        const id = idOf(rel, base);
        (pages.get(id) ?? pages.set(id, new Set()).get(id)).add(lang);
      }
    }
  }
  return pages;
}

// ---- record ----------------------------------------------------------------------------
export function readRecord(v, id) {
  const p = recordPath(id);
  return v.exists(p) ? JSON.parse(v.read(p)) : null;
}
function writeRecordFile(id, rec) {
  const langs = FOLDERS.filter((l) => rec.langs[l]);
  const body = langs.map((l) => `    ${JSON.stringify(l)}: ${JSON.stringify(rec.langs[l])}`).join(',\n');
  // The versions each language's hashes were normalized against, so a version that was current then still reads as its token.
  const vl = langs.filter((l) => rec.versions?.[l] && Object.keys(rec.versions[l]).length);
  const vers = vl.length ? `,\n  "versions": {\n${vl.map((l) => `    ${JSON.stringify(l)}: ${JSON.stringify(rec.versions[l])}`).join(',\n')}\n  }` : '';
  const text = `{\n  "page": ${JSON.stringify(id)},\n  "english": ${JSON.stringify(rec.english)},\n  "langs": {\n${body}\n  }${vers}\n}\n`;
  const p = join(ROOT, recordPath(id));
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
}
// Say that a language's translation of a page was made from this English text. `english` is the text and `path`
// where it lives; the default is the page as it is now. Fails when the translation does not have one line per
// English segment, because then the two lists do not line up and nothing could be flagged against it.
export function record(id, lang, { english, path, v = view() } = {}) {
  const ep = path ?? englishPath(v, id);
  if (!ep) throw new Error(`${id}: there is no English page to record against`);
  const text = english ?? v.read(ep);
  const vm = versionMap(v);
  const h = hashes(text, vm);
  const tp = translationPath(v, lang, id);
  if (!tp) throw new Error(`${id} ${lang}: there is no translated page to record`);
  const n = segs(parse(v.read(tp))).length;
  if (n !== h.length) throw new Error(`${id} ${lang}: ${tp} has ${n} segments and the English has ${h.length}, so they do not line up`);
  const rec = readRecord(v, id) ?? { page: id, english: ep, langs: {} };
  rec.english = ep;
  rec.langs[lang] = h;
  rec.versions = { ...(rec.versions ?? {}), [lang]: vm };
  writeRecordFile(id, rec);
  return h.length;
}

// ---- diff ------------------------------------------------------------------------------
// Longest common subsequence of two hash lists: which positions of each list are the same segment.
function align(a, b) {
  const n = a.length, m = b.length;
  const dp = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
  const keptA = new Array(n).fill(-1), keptB = new Array(m).fill(-1);
  let i = 0, j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) { keptA[i] = j; keptB[j] = i; i++; j++; } else if (dp[i + 1][j] >= dp[i][j + 1]) i++; else j++;
  }
  return { keptA, keptB };
}
// What changed in the English since the recorded list: `changed` are positions (0-based) in the current English
// that have no matching recorded segment, `removed` are positions in the recorded list that no longer exist,
// `carry[j]` is, for each current segment, the recorded position whose translation still applies (or -1).
export function diff(recorded, current) {
  const { keptA, keptB } = align(recorded, current);
  return {
    changed: keptB.flatMap((k, j) => (k < 0 ? [j] : [])),
    removed: keptA.flatMap((k, i) => (k < 0 ? [i] : [])),
    carry: keptB,
  };
}

// The hashes of the current English to compare against one language's recorded list. A segment counts as the
// recorded one when it matches with the versions normalized against today's releases (a release moved), against the
// releases of the day it was recorded (an older line that was the latest then), or as written (a record made before
// versions were normalized). Otherwise it takes today's normalized hash, which is what the next record writes.
export function currentHashes(text, v, recorded, recordedVersions = null) {
  const have = new Set(recorded);
  const now = versionMap(v);
  return segs(parse(text)).map((x) => {
    const c = [hashSeg(normalizeVersions(x, now)), recordedVersions ? hashSeg(normalizeVersions(x, recordedVersions)) : null, hashSeg(x)];
    return c.find((h) => h && have.has(h)) ?? c[0];
  });
}

// ---- the check -------------------------------------------------------------------------
const clip = (s, n = 420) => (s.length > n ? s.slice(0, n - 1) + '...' : s);

// Everything wrong with the translations, as { stale, problems }. `stale` is one entry per page and set of languages
// that share the same stale segments.

// ---- release notes ---------------------------------------------------------------------
// Every release page (src/content/docs/releases/<product>-<version>.md) carries its 13 translations, so a new release
// cannot ship in English alone. src/i18n-releases-pending.json lists the release pages that were English only when this
// rule began. It only shrinks: a release page that is not translated and not listed fails, and a listed page that is
// translated fails until it is taken off the list (`releases --write`).
export const PENDING = 'src/i18n-releases-pending.json';
const RELEASE_PAGE = /^releases\/(?:flow|cascade|hotloop|codesys|transmitter)-\d/;
export function releasePages(v) {
  return v.walk(CONTENT).map((rel) => idOf(rel, CONTENT)).filter((id) => RELEASE_PAGE.test(id)).sort();
}
export function pendingReleases(v) {
  return v.exists(PENDING) ? JSON.parse(v.read(PENDING)).pages ?? [] : [];
}
function releaseProblems(v, pages) {
  const problems = [];
  const listed = new Set(pendingReleases(v));
  for (const id of releasePages(v)) {
    const have = pages.get(id) ?? new Set();
    const missing = FOLDERS.filter((l) => !have.has(l));
    if (!missing.length) { if (listed.has(id)) problems.push(`${id}: is translated in every language and still on the pending list ${PENDING}. Run: node scripts/i18n-source.mjs releases --write`); continue; }
    if (!listed.has(id)) problems.push(`${id}: a release page needs its 13 translations and has none in ${missing.join(' ')}. Translate it in the same pull request as the release notes (README, Translations).`);
  }
  const known = new Set(releasePages(v));
  for (const id of listed) if (!known.has(id)) problems.push(`${id}: is on the pending list ${PENDING} and there is no such release page. Run: node scripts/i18n-source.mjs releases --write`);
  return problems;
}

export function examine(overlay = new Map()) {
  const v = view(overlay);
  const stale = [];
  const problems = [];
  const pages = translatedPages(v);
  // A record whose page has no translation left.
  for (const rel of v.walk(RECORDS)) {
    if (!rel.endsWith('.json')) continue;
    const id = idOf(rel, RECORDS).replace(/\.json$/, '').replace(/__/g, '/');
    const rec = readRecord(v, id);
    for (const lang of Object.keys(rec?.langs ?? {})) if (!pages.get(id)?.has(lang)) problems.push(`${id} ${lang}: has a record in ${rel} and no translated page. Delete that language from the record.`);
  }
  for (const [id, langs] of [...pages].sort((a, b) => a[0].localeCompare(b[0]))) {
    const ep = englishPath(v, id);
    if (!ep) { problems.push(`${id}: translated in ${[...langs].join(' ')} and there is no English page ${id}`); continue; }
    const etext = v.read(ep);
    const curSegs = segs(parse(etext));
    const lines = segLines(etext);
    const rec = readRecord(v, id);
    const groups = new Map(); // key of changed+removed -> { langs, changed, removed }
    for (const lang of FOLDERS.filter((l) => langs.has(l))) {
      const tp = translationPath(v, lang, id);
      const have = segs(parse(v.read(tp))).length;
      const r = rec?.langs?.[lang];
      if (!r) { problems.push(`${id} ${lang}: ${tp} has no record of the English it was made from. Run: node scripts/i18n-source.mjs record ${id} ${lang}`); continue; }
      if (have !== r.length) { problems.push(`${id} ${lang}: ${tp} has ${have} segments and its record says it was made from ${r.length}. It no longer lines up with its source.`); continue; }
      const cur = currentHashes(etext, v, r, rec.versions?.[lang]);
      const d = diff(r, cur);
      if (!d.changed.length && !d.removed.length) continue;
      const key = d.changed.join(',') + '|' + d.removed.join(',');
      (groups.get(key) ?? groups.set(key, { langs: [], changed: d.changed, removed: d.removed }).get(key)).langs.push(lang);
    }
    for (const g of groups.values()) {
      stale.push({
        id, english: ep, langs: g.langs,
        changed: g.changed.map((j) => ({ segment: j + 1, line: lines[j], english: curSegs[j] })),
        removed: g.removed.map((i) => i + 1),
      });
    }
  }
  problems.push(...releaseProblems(v, pages));
  return { stale, problems, v };
}

export function anchorProblems(v, { fix = false } = {}) {
  const problems = [];
  const fixes = new Map(); // file -> [from, to]
  const pages = translatedPages(v);
  const slugsOf = (p) => headingSlugs(v.read(p));
  for (const [id, langs] of pages) {
    for (const lang of langs) {
      const files = [`${PINNED}/${lang}/${id}.md`, `${CONTENT}/${lang}/${id}.md`, `${CONTENT}/${lang}/${id}.mdx`].filter((p) => v.exists(p));
      const text = v.read(files[files.length - 1]);
      let fence = null;
      for (const line of text.split('\n')) {
        const st = fenceStep(fence, line);
        fence = st.open;
        if (st.code) continue;
        for (const m of line.matchAll(/(?<!!)\]\(([^)\s]*)#([^)\s]+)\)/g)) {
          const path = m[1], anchor = m[2];
          let target = id;
          if (path !== '') {
            if (!path.startsWith(`/${lang === 'zh-hans' ? 'zh-hans' : lang}/`)) continue;
            target = path.replace(new RegExp(`^/${lang}/`), '').replace(/\/$/, '');
            if (target === '') target = 'index';
          }
          const tp = ['', '/index'].map((s) => translationPath(v, lang, target + s)).find(Boolean);
          const ep = ['', '/index'].map((s) => englishPath(v, target + s)).find(Boolean);
          if (!tp && !ep) { problems.push(`${id} ${lang}: link ${path}#${anchor} goes to a page that does not exist`); continue; }
          const T = slugsOf(tp ?? ep);
          if (T.includes(anchor)) continue;
          const E = ep ? slugsOf(ep) : [];
          const i = E.indexOf(anchor);
          const better = tp && i >= 0 && E.length === T.length ? T[i] : null;
          problems.push(`${id} ${lang}: link ${path}#${anchor} is not a heading of ${tp ?? ep}${better ? `, it is #${better} there` : ''}`);
          if (better) for (const f of files) {
            (fixes.get(f) ?? fixes.set(f, []).get(f)).push([`](${path}#${anchor})`, `](${path}#${better})`]);
          }
        }
      }
    }
  }
  if (fix) {
    let n = 0;
    for (const [f, list] of fixes) {
      let t = readFileSync(join(ROOT, f), 'utf8');
      for (const [a, b] of list) if (t.includes(a)) { t = t.split(a).join(b); n++; }
      writeFileSync(join(ROOT, f), t);
    }
    return { problems, fixed: n };
  }
  return { problems, fixed: 0 };
}

// What the sync and the build print and fail on. Returns true when everything lines up.
export function report(overlay = new Map(), out = console.log) {
  const { stale, problems, v } = examine(overlay);
  const a = anchorProblems(v);
  const all = [...problems, ...a.problems];
  const pagesTotal = translatedPages(v).size;
  if (stale.length) {
    out(`i18n-source: ${stale.length} translated page set(s) are behind their English. Retranslate exactly these segments, then run the builder (it records the new English):`);
    for (const s of stale) {
      out(`  STALE  ${s.id}  [${s.langs.join(' ')}]  English ${s.english}`);
      for (const c of s.changed) out(`    segment ${c.segment}  line ${c.line}: ${clip(c.english)}`);
      if (s.removed.length) out(`    the English no longer has the segment(s) it was translated from at recorded position ${s.removed.join(', ')}; those translations are dropped`);
    }
  }
  if (all.length) { out(`i18n-source: ${all.length} problem(s)`); for (const p of all) out(`  FAIL  ${p}`); }
  if (!stale.length && !all.length) out(`i18n-source: ${pagesTotal} translated page(s) match the English they were made from, and every link between them lands on a heading`);
  return !stale.length && !all.length;
}

// ---- release versions in translations ---------------------------------------------------
// A translation holds the version its English said the day it was made. The hash treats the latest release as a token, so a
// new release does not mark the page stale, and that is also why nothing moved the number: a translated page kept saying 4.24.0
// after 4.24.1 shipped. bump() closes that. For every translated page whose recorded versions are behind the sync's, and whose
// only difference from the English is the version, it rewrites the old version in each segment where the English says the
// latest one, in the translation's own line, and records the page again. A segment the English really changed is left for
// the retranslation, and a version in a segment where the English names an older release is history and is not touched.
export function bump({ dry = false, v = view() } = {}) {
  const now = versionMap(v);
  const done = [];
  for (const [id, langs] of translatedPages(v)) {
    const ep = englishPath(v, id);
    const rec = ep ? readRecord(v, id) : null;
    if (!rec) continue;
    const etext = v.read(ep);
    const eseg = segs(parse(etext));
    for (const lang of FOLDERS.filter((l) => langs.has(l))) {
      const r = rec.langs?.[lang], rv = rec.versions?.[lang];
      if (!r || !rv) continue;
      const moved = Object.keys(now).filter((k) => rv[k] && now[k] && rv[k] !== now[k]);
      if (!moved.length) continue;
      const tp = translationPath(v, lang, id);
      const ttext = v.read(tp);
      const tsegs = segs(parse(ttext));
      if (tsegs.length !== r.length) continue;
      const d = diff(r, currentHashes(etext, v, r, rv));
      if (d.changed.length || d.removed.length) continue;
      const starts = segLines(ttext);
      const lines = ttext.split('\n');
      let touched = 0;
      d.carry.forEach((k, j) => {
        if (k < 0) return;
        let seg = tsegs[k];
        const before = seg;
        for (const name of moved) {
          if (!normalizeVersions(eseg[j], { [name]: now[name] }).includes(`{{${name}`)) continue;
          const o = /^(\d+)\.(\d+)\.(\d+)$/.exec(rv[name]), n = /^(\d+)\.(\d+)\.(\d+)$/.exec(now[name]);
          if (!o || !n) continue;
          const swap = (a, b) => { seg = seg.replace(new RegExp(`(?<![\\w.-])${esc(a)}(?![\\w]|\\.\\d|-\\d)`, 'g'), b); };
          swap(rv[name], now[name]);
          seg = seg.replace(new RegExp(`(?<![\\w.-])${esc(`${o[1]}.${o[2]}`)}\\.x\\b`, 'g'), `${n[1]}.${n[2]}.x`);
          swap(`${o[1]}.${o[2]}`, `${n[1]}.${n[2]}`);
        }
        if (seg === before) return;
        const first = starts[k] - 1, count = before.split('\n').length;
        seg.split('\n').forEach((ln, i) => { lines[first + i] = ln; });
        touched++;
      });
      if (!touched) continue;
      done.push({ id, lang, touched });
      if (!dry) {
        writeFileSync(join(ROOT, tp), lines.join('\n'));
        record(id, lang);
      }
    }
  }
  return done;
}

// ---- command line -----------------------------------------------------------------------
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [cmd = 'check', ...rest] = process.argv.slice(2);
  if (cmd === 'check') process.exit(report() ? 0 : 1);
  else if (cmd === 'stale') {
    const { stale, problems } = examine();
    console.log(JSON.stringify({ stale, problems }, null, 2));
    process.exit(stale.length || problems.length ? 1 : 0);
  } else if (cmd === 'links') {
    const v = view();
    const r = anchorProblems(v, { fix: rest.includes('--fix') });
    r.problems.forEach((p) => console.log(p));
    console.log(rest.includes('--fix') ? `i18n-source: repaired ${r.fixed} link(s)` : `i18n-source: ${r.problems.length} link problem(s)`);
    process.exit(rest.includes('--fix') ? 0 : r.problems.length ? 1 : 0);
  } else if (cmd === 'record') {
    const [id, ...langs] = rest;
    if (!id) { console.error('usage: i18n-source.mjs record <page> [lang ...]'); process.exit(2); }
    for (const l of langs.length ? langs : FOLDERS) console.log(`recorded ${id} ${l}: ${record(id, l)} segments`);
  } else if (cmd === 'bump') {
    const done = bump({ dry: rest.includes('--dry') });
    for (const d of done) console.log(`${rest.includes('--dry') ? 'would bump' : 'bumped'} ${d.id} ${d.lang}: ${d.touched} line(s)`);
    console.log(`i18n-source: ${done.length} translation(s) ${rest.includes('--dry') ? 'hold' : 'held'} an older release version`);
    process.exit(rest.includes('--dry') && done.length ? 1 : 0);
  } else if (cmd === 'releases') {
    const v = view();
    const pages = translatedPages(v);
    const todo = releasePages(v).filter((id) => FOLDERS.some((l) => !pages.get(id)?.has(l)));
    if (rest.includes('--write')) {
      const keep = pendingReleases(v).filter((id) => todo.includes(id));
      writeFileSync(join(ROOT, PENDING), JSON.stringify({ pages: keep }, null, 2) + '\n');
      console.log(`i18n-source: ${keep.length} release page(s) still pending`);
    } else if (rest.includes('--init')) {
      writeFileSync(join(ROOT, PENDING), JSON.stringify({ pages: todo }, null, 2) + '\n');
      console.log(`i18n-source: ${todo.length} release page(s) written to ${PENDING}`);
    } else { todo.forEach((id) => console.log(id)); console.log(`i18n-source: ${todo.length} release page(s) without their 13 translations`); }
  } else if (cmd === 'migrate') {
    // One time: records made before versions were normalized hold the hash of the English as written. Where a segment
    // is still exactly what was recorded, store its normalized hash and the versions, so the next release does not flag it.
    const v = view();
    const vm = versionMap(v);
    let n = 0;
    for (const rel of v.walk(RECORDS)) {
      if (!rel.endsWith('.json')) continue;
      const id = idOf(rel, RECORDS).replace(/\.json$/, '').replace(/__/g, '/');
      const rec = readRecord(v, id);
      const ep = englishPath(v, id);
      if (!rec || !ep) continue;
      const cur = segs(parse(v.read(ep)));
      for (const lang of Object.keys(rec.langs)) {
        if (rec.versions?.[lang]) continue;
        const r = rec.langs[lang];
        const raw = cur.map(hashSeg);
        const { keptB } = align(r, raw);
        const next = [...r];
        keptB.forEach((i, j) => { if (i >= 0) next[i] = hashSeg(normalizeVersions(cur[j], vm)); });
        rec.langs[lang] = next;
        rec.versions = { ...(rec.versions ?? {}), [lang]: vm };
        n++;
      }
      writeRecordFile(id, rec);
    }
    console.log(`i18n-source: migrated ${n} language record(s) to normalized versions`);
  } else { console.error(`unknown command ${cmd}`); process.exit(2); }
}
