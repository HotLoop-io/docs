// The License and Terms pages are the canonical LICENSE.md and TERMS.md from
// HotLoop-io/HotLoop-io, wrapped in a title and nothing else. The legal text is never
// edited here, so this site cannot say something the license doesn't.
//
//   node scripts/sync-legal.mjs --license <LICENSE.md> [--terms <TERMS.md>]    write the pages
//   node scripts/sync-legal.mjs --check --license <LICENSE.md> [--terms <TERMS.md>]
//                                    fail if a committed page differs from what the file renders
//
// A page is only written when the file is the new one. LICENSE.md has to be HotLoop's
// Business Source License, and until it is, the old text stays off this site. In check
// mode a missing committed page is fine for the same reason, and a stale one is not.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MARK = '# generated by scripts/sync-legal.mjs';

const PAGES = {
  license: {
    out: 'license.md',
    title: 'License',
    description: "HotLoop's Business Source License 1.1, the text every HotLoop product is under, mirrored from the canonical copy in the HotLoop-io organization.",
    isNew: (t) => /Business Source License/i.test(t),
    canonical: 'https://github.com/HotLoop-io/HotLoop-io/blob/main/LICENSE.md',
    lead: 'Every HotLoop product is under this license. The text below is mirrored from the canonical copy and is what decides things, so it wins over anything else on this site.',
  },
  terms: {
    out: 'terms.md',
    title: 'Terms',
    description: 'The terms that go with HotLoop, mirrored from the canonical copy in the HotLoop-io organization, so this site cannot say something they do not.',
    // The canonical file still carries its effective-date placeholder, and a page with a bracketed blank in it does not go live.
    isNew: (t) => !/\[EFFECTIVE DATE\]/.test(t),
    canonical: 'https://github.com/HotLoop-io/HotLoop-io/blob/main/TERMS.md',
    lead: 'The text below is mirrored from the canonical copy and is what decides things, so it wins over anything else on this site.',
  },
};

export function render(kind, raw) {
  const p = PAGES[kind];
  const text = raw.replace(/\r\n/g, '\n').replace(/^# .*\n+/, '').trim();
  if (/[—–]/.test(text)) throw new Error(`${kind}: the canonical text contains an em or en dash. It is legal text, so it is not rewritten here. Fix it in HotLoop-io/HotLoop-io.`);
  return `---\n${MARK}\ntitle: ${JSON.stringify(p.title)}\ndescription: ${JSON.stringify(p.description)}\neditUrl: false\n---\n\n${p.lead} The canonical copy is [on GitHub](${p.canonical}).\n\n${text}\n`;
}

export function status(kind, raw) {
  return raw != null && PAGES[kind].isNew(raw);
}

export function outPath(kind) { return join(ROOT, 'src/content/docs', PAGES[kind].out); }

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const a = process.argv.slice(2);
  const val = (n) => { const i = a.indexOf(`--${n}`); return i > -1 ? readFileSync(a[i + 1], 'utf8') : null; };
  const check = a.includes('--check');
  let bad = 0;
  for (const kind of ['license', 'terms']) {
    const raw = val(kind);
    if (!status(kind, raw)) { console.log(`${kind}: the canonical file is not the new text yet, so there is no ${kind} page`); continue; }
    const page = render(kind, raw);
    const p = outPath(kind);
    if (check) {
      if (!existsSync(p) || readFileSync(p, 'utf8').replace(/\r\n/g, '\n') !== page) { console.log(`${kind}: committed page differs from the canonical file`); bad++; } else console.log(`${kind}: matches`);
    } else {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, page);
      console.log(`${kind}: wrote ${p}`);
    }
  }
  process.exit(bad ? 1 : 0);
}
