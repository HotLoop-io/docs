// Pinned pages: hand-written, with the release versions filled in.
const pinned = [];
if (existsSync(PINNED)) {
  const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));
  for (const f of walk(PINNED)) {
    const rel = relative(PINNED, f).split('\\').join('/');
    let t = readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
    // A pinned page says which release it was last read against. When a newer release
    // is out, somebody reads it again and bumps the line, or the sync stops here.
    const rv = /^reviewed: (\w+)=(\S+)\n/m.exec(t);
    if (rv) {
      if (releases[rv[1]].version !== rv[2] && !flag('allow-stale-pinned')) fail(`${rel} was last read against ${rv[1]} ${rv[2]}, and the latest release is ${releases[rv[1]].version}. Read the page against that release, then change its reviewed: line.`);
      t = t.replace(rv[0], '');
    }
    t = t.replace(/\{\{(hotloop|flow|cascade)\}\}/g, (_, r) => releases[r].version).replace(/\{\{LICENSE_URL\}\}/g, licenseUrl());
    if (/\{\{/.test(t)) fail(`${rel}: an unfilled {{token}}`);
    t = t.replace(/^---\n/, `---\n${MARK}\n`).replace(/^(---\n[^]*?\n)(---\n)/, (m, a, b) => (/editUrl:/.test(a) ? m : a + 'editUrl: false\n' + b));
    out.set(rel, t);
    pinned.push(rel);
    log2.push(`pinned   ${rel}`);
  }
}

